/* USB                                                                 */
/* ------------------------------------------------------------------ */
/*
 * VID/PID。
 *
 * 0xCAFE は USB-IF に登録された VID ではなく、TinyUSB のサンプルが
 * 既定で使っていることから趣味の実装で慣習的に使われている値。
 * 自分の手元で使うぶんには何の問題もないが、正式な割り当てではない
 * ので、同じ慣習に乗った別のデバイスと PID までぶつかると
 * ホスト側の学習が混ざる可能性はある。
 * 筋を通すなら pid.codes (VID 0x1209) に PID を申請する道もある。
 *
 * なお、ここを変えてもブートローダの列挙には影響しない。
 * ISP ツールが見ているのは WCH 固有の 0x4348/0x55E0 で、
 * こちらはアプリケーション側の申告だけ。書き込み手順は変わらない。
 */
#define USB_VID 0xCAFE
#define USB_PID 0x9002

/*
 * シリアル番号をチップ固有 ID から作るか。
 *   1: チップ固有 ID (40bit) を 10 桁の 16 進で出す (既定)
 *      0x3FFA が最上位バイト、0x3FFC-0x3FFF が下位 32bit
 *   0: 固定文字列 "0000000001"
 *
 * ホストは VID/PID/シリアルの組で個体を覚えるので、同じ firmware を
 * 焼いた基板を複数挿すなら 1 のままにしておくこと。0 にすると
 * macOS の /dev/cu.usbmodem* が衝突したり、片方に対する設定が
 * もう片方に効いたりする。
 *
 * 逆に、挿し替えるたびにホストが「新しいデバイス」として扱うのが
 * 邪魔な場面 (テストの自動化など) では 0 が便利。
 */
#define SERIAL_FROM_CHIP_ID 1

/*
 * 端点バッファ用に xRAM の先頭から確保しておく領域。
 *   0x0000 EP0  64B  制御 (OUT と IN で共用)
 *   0x0040 EP1  64B  HID レポート。IN のみ
 *   0x0080 EP2 128B  CDC バルク。IN と OUT
 *   0x0100 EP3  64B  CDC 通知。IN のみ
 *
 * 単一バッファモードでは、有効にした方向のぶんだけが UEPn_DMA から
 * 低位→高位に 64 バイト単位で並ぶ (受信が先)。配置とサイズは
 * src/usb.c が MOD レジスタの値から導いて静的検査している。
 *
 * Makefile の --xram-loc と --xram-size をこの値に合わせてあるので、
 * ここを動かすときは Makefile も直すこと。実際の配置と重なりは
 * src/usb.c の静的検査が見ている。
 */
#define USB_RAM_END 0x0140

/*
 * ホストがサスペンドしている間どうするか。
 * この 2 つは両立しない。理由は WAKE_CTRL の起床要因に P1.7 が無く、
 * MCU が眠るとタッチキーも止まってしまうため。
 *
 * SUSPEND_SLEEP  低消費優先
 *   PCON の PD で CH552 ごと眠り、USB イベントで起きる。
 *   bMaxPower=100mA (1 unit load) に許されるサスペンド電流は 500uA で、
 *   24MHz で回したままでは到底届かないので、規格に寄せるならこちら。
 *   代償: 眠っている間はタッチもタイマも止まる。触っても反応せず、
 *   長押しの DFU も効かない。モード B の 1 分カウントも止まる
 *   (ホストが寝ているなら動かす必要もないので実害はない)。
 *
 * SUSPEND_WAKE   タッチ起床優先
 *   起きたまま待ち、タッチされたら USB のリモートウェイクアップで
 *   ホストを起こす。消費電流は mA オーダーのまま。
 *   ホスト側が SET_FEATURE(DEVICE_REMOTE_WAKEUP) で許可していないと
 *   信号は送らない (規格上そうしなければならない)。
 *   macOS が実際に起きるかは機種と蓋の開閉状態に依存するので、
 *   動かなくてもファーム側の問題とは限らない。
 */
#define SUSPEND_SLEEP 0
#define SUSPEND_WAKE  1

#define SUSPEND_POLICY SUSPEND_SLEEP

/*
 * リモートウェイクアップを申告してからホストが許可するまでの
 * 猶予。USB 規格ではバスがアイドルになってから 5ms 以上空けてから
 * レジューム信号を出すことになっているので、その保険。
 */
#define WAKEUP_GUARD_MS 20

#define USB_MAX_POWER_MA     100  /* bMaxPower。2mA 単位に丸められる    */
#define USB_HID_INTERVAL_MS   10  /* 割り込み IN のポーリング間隔       */

/* CDC コンソールで monitor を有効にしたときの出力間隔 */
#define CONSOLE_MONITOR_MS   200

/*
 * 1200 baud で開いて閉じたらブートローダへ、という開発用のトリガ。
 *
 * macOS の /dev/cu.usbmodem* は誰でも開けるので、これを有効にすると
 * ローカルの任意のプロセスがこのデバイスをブートローダに落として
 * 任意のファームを書き込めることになる。キーボードとして列挙する
 * デバイスである以上、配布用ビルドでは 0 にしてタッチ長押しだけに
 * しておく方が安全。開発中は 1 が便利。
 */
#define CDC_DFU_1200BAUD 1

/*
 * 送信リングが満杯のとき、ホストが吐き出すのを何 ms まで待つか。
 * これを超えたら、その出力の残りは捨てる (次に吐き出せた時点で復帰)。
 * 待っている間もウォッチドッグには餌をやるので、ここを長くしても
 * リセットはしないが、その間タッチもモードも止まる。
 */
#define CDC_TX_WAIT_MS 20

/* ------------------------------------------------------------------ */
/* ウォッチドッグ                                                      */
/* ------------------------------------------------------------------ */
/*
 * カウンタのクロックは Fsys/65536。24MHz なら 1 カウント 2.73ms で、
 * 8bit なので 0 から数えて約 700ms でリセットがかかる。
 * メインループの先頭で WDOG_COUNT に 0 を書いて餌をやる。
 *
 * ブロックする処理で一番長いのは touch_recalibrate()。1 回ぶんは
 * (TOUCH_DISCARD_SAMPLES + TOUCH_CAL_SAMPLES) x 1ms = 72ms だが、
 * **やり直し (TOUCH_CAL_RETRY) は窓ごと繰り返す**ので最悪 216ms、
 * 測定系が黙っていると 1 サンプル 8ms まで伸びて 576ms になる。
 * さらに 1 周回で 2 回呼ばれる経路 (サスペンド復帰 + コンソールの z) が
 * あるため、touch_recalibrate() は中でサンプルごとに餌をやっている。
 * 較正のサンプル数を増やす場合も、その中で餌をやっているぶん
 * ここが破綻することはない。
 */
#define WATCHDOG_ENABLE 1

/* ------------------------------------------------------------------ */
/* モードごとの色 (R, G, B の順で指定する。GRB 変換は neo.c 側)        */
/* ------------------------------------------------------------------ */
#define COLOR_IDLE_R    0x00   /* モード A: 何もしない -> 緑             */
#define COLOR_IDLE_G    0xFF
#define COLOR_IDLE_B    0x00

#define COLOR_WIGGLE_R  0xFF   /* モード B: マウス移動 -> 赤             */
#define COLOR_WIGGLE_G  0x00
#define COLOR_WIGGLE_B  0x00

#define COLOR_NOUSB_R   0xFF   /* 未列挙 -> 橙                           */
#define COLOR_NOUSB_G   0x50
#define COLOR_NOUSB_B   0x00

#define COLOR_LEARN_R   0xFF   /* 閾値の学習に成功 -> マゼンタ           */
#define COLOR_LEARN_G   0x00
#define COLOR_LEARN_B   0xFF

/*
 * 学習に失敗したときの色。モード B の赤と紛れないよう黄にしてある。
 * 未列挙の橙とも、緑成分が 0x50 と 0xFF で見た目がはっきり違う。
 */
#define COLOR_FAIL_R    0xFF
#define COLOR_FAIL_G    0xFF
#define COLOR_FAIL_B    0x00

#define COLOR_TOUCH_R   0x00   /* タッチ検出中 -> 青                     */
#define COLOR_TOUCH_G   0x00
#define COLOR_TOUCH_B   0xFF

/*
 * 学習窓に入っているあいだの色 -> シアン。
 * 青から緑成分だけが増える。青 (窓の手前) と白 (窓の先) の中間に
 * あたる色なので、入り口と出口のどちらへ向かっているかが分かる。
 */
#define COLOR_LEARNWIN_R 0x00
#define COLOR_LEARNWIN_G 0xFF
#define COLOR_LEARNWIN_B 0xFF

#define COLOR_DFU_R     0xFF   /* DFU 突入直前の予告 -> 白               */
#define COLOR_DFU_G     0xFF
#define COLOR_DFU_B     0xFF

#endif /* CONFIG_H */
